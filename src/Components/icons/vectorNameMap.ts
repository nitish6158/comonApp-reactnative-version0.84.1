export function mapVectorIconName(name: string | undefined | null): IconName {
  if (!name) return "info";
  const key = String(name).trim();
  const lower = key.toLowerCase();
  return (
    VECTOR_TO_APP_ICON[key] ??
    VECTOR_TO_APP_ICON[lower] ??
    VECTOR_TO_APP_ICON[lower.replace(/_/g, "-")] ??
    "info"
  );
}
